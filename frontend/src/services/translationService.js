export const translateText = async (text, sourceLang, targetLang) => {
  if (!text || !text.trim()) return '';
  const url = `https://api.mymemory.translated.net/get?q=${encodeURIComponent(text)}&langpair=${sourceLang}|${targetLang}`;
  try {
    const response = await fetch(url);
    if (!response.ok) throw new Error('API request failed');
    const data = await response.json();
    if (data.responseStatus === 200) {
      return data.responseData.translatedText;
    }
    throw new Error(data.responseDetails || 'API error');
  } catch (err) {
    console.warn(`Translation API failed for text: "${text.slice(0, 20)}...", using fallback mock suffix.`, err);
    return mockTranslate(text, targetLang);
  }
};

export const translateStory = async (title, content, sourceLang, targetLang) => {
  const normalizedTitle = title.trim();
  
  // 1. Check if we have pre-defined high-quality translations
  if (FALLBACK_TRANSLATIONS[normalizedTitle] && FALLBACK_TRANSLATIONS[normalizedTitle][targetLang]) {
    return {
      title: FALLBACK_TRANSLATIONS[normalizedTitle][targetLang].title,
      content: FALLBACK_TRANSLATIONS[normalizedTitle][targetLang].content
    };
  }

  // 2. Query MyMemory Translation API chunk-by-chunk
  try {
    // Translate Title
    const translatedTitle = await translateText(title, sourceLang, targetLang);

    // Split content by paragraph to bypass length limit (1000 characters)
    const paragraphs = content.split('\n\n');
    const translatedParagraphs = await Promise.all(
      paragraphs.map(async (p) => {
        if (!p.trim()) return '';
        // If single paragraph is very long, split it by sentence-ending punctuation
        if (p.length > 800) {
          const sentences = p.match(/[^.!?]+[.!?]+(\s|$)/g) || [p];
          const translatedSentences = await Promise.all(
            sentences.map(s => translateText(s, sourceLang, targetLang))
          );
          return translatedSentences.join('');
        }
        return translateText(p, sourceLang, targetLang);
      })
    );

    return {
      title: translatedTitle,
      content: translatedParagraphs.join('\n\n')
    };
  } catch (error) {
    console.error('Failed to translate story:', error);
    return {
      title: title,
      content: content
    };
  }
};

